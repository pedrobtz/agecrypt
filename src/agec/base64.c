void base64encode(uchar *in, uchar *out, usize inlen, usize *outlen, int pad)
{
	int s;
	uint i, j;
	uchar c, l;

	s = 0;
	l = 0;
	for(i = j = 0; i < inlen; i++) {
		if(pad && j > 0 && (j + 1) % (LINELEN + 1) == 0)
			out[j++] = '\n';
		c = in[i];
		switch(s) {
		case 0:
			s = 1;
			out[j++] = etable[(c >> 2) & 0x3f];
			break;
		case 1:
			s = 2;
			out[j++] = etable[((l & 0x3) << 4) | ((c >> 4) & 0xf)];
			break;
		case 2:
			s = 0;
			out[j++] = etable[((l & 0xf) << 2) | ((c >> 6) & 0x3)];
			out[j++] = etable[c & 0x3f];
			break;
		}
		l = c;
	}
	switch(s) {
	case 0:
		if(pad)
			out[j++] = '\n';
		break;
	case 1:
		out[j++] = etable[(l & 0x3) << 4];
		if(pad) {
			out[j++] = PAD;
			out[j++] = PAD;
			out[j++] = '\n';
		}
		break;
	case 2:
		out[j++] = etable[(l & 0xf) << 2];
		if(pad) {
			out[j++] = PAD;
			out[j++] = '\n';
		}
		break;
	}
	*outlen = j;
}

/*
 * Size of the output buffer must be at least B64DBUFLEN(len),
 * where len is the number of base64 characters only.
 */
int
base64decode(uchar *in, uchar *out, usize inlen, usize *outlen, int pad)
{
	usize lastlen = 0;
	uint i, j, k, line;
	uchar c, next = 0;

	if(pad) {
		lastlen = inlen - (inlen - inlen % (LINELEN + 1));
		if(lastlen > 0 && (lastlen - 1) & 3) 
			return 0; /* last line is wrongly padded */
	}
	for(i = j = line = 0; i < inlen; i++) {
		if(pad && i > 0 && (i + 1) % (LINELEN + 1) == 0) {
			if(in[i] != '\n')
				return 0;
			line++;
			continue;
		} else if(in[i] == PAD) {
			if(!pad)
				return 0;
			break;
		} else if(in[i] < DFIRST || in[i] > DLAST) {
			if(lastlen && i + 1 == inlen && in[i] == '\n')
				break;
			return 0;
		}
		c = dtable[(uchar)in[i]];
		if(c == 0x80)
			return 0;
		switch((i - line) & 0x3) {
		case 0:
			out[j] = (c << 2) & 0xff;
			break;
		case 1:
			out[j++] |= (c >> 4) & 0x3;
			next = (c & 0xf) << 4;
			break;
		case 2:
			out[j] = next;
			out[j++] |= (c >> 2) & 0xf;
			next = (c & 0x3) << 6;
			break;
		case 3:
			out[j] = next;
			out[j++] |= c;
			break;
		}
	}
	if(pad) {
		if(i + 2 + 1 < inlen)
			return 0;
		for(k = i; k + 1 < inlen; k++) {
			if(in[k] != PAD)
				return 0;
		}
	}
	if((i - line) & 0x3 && next)
		return 0;    /* non-canonical */
	*outlen = j;
	return 1;
}
